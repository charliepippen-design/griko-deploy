CREATE POLICY "Allow public read on carmine_lessons" ON public.carmine_lessons FOR SELECT TO public USING (true);

DROP POLICY IF EXISTS "Allow public read on carmine_rules" ON public.carmine_rules;
CREATE POLICY "Allow public read on carmine_rules" ON public.carmine_rules FOR SELECT TO public USING (true);

DROP POLICY IF EXISTS "Allow public read on carmine_lexemes" ON public.carmine_lexemes;
CREATE POLICY "Allow public read on carmine_lexemes" ON public.carmine_lexemes FOR SELECT TO public USING (true);

DROP POLICY IF EXISTS "Allow public read on carmine_occurrences" ON public.carmine_occurrences;
CREATE POLICY "Allow public read on carmine_occurrences" ON public.carmine_occurrences FOR SELECT TO public USING (true);
